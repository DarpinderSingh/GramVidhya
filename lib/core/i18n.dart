/// Persist the selected language to Hive and notify listeners.
Future<void> setLanguage(String code) async {
  appLang.value = code;
  final box = Hive.box('app');
  await box.put('lang', code);
}

/// Restore persisted language on startup. Call from main() after Hive.initFlutter().
Future<void> restoreLanguage() async {
  final box = Hive.box('app');
  final saved = box.get('lang', defaultValue: 'en') as String;
  if (langNames.containsKey(saved)) {
    appLang.value = saved;
  }
}

