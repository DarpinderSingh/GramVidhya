/// Template replacement: tr('income_label').replaceAll('{n}', '2.5')
String trf(String k, Map<String, String> args) {
  var s = tr(k);
  for (final e in args.entries) {
    s = s.replaceAll('{${e.key}}', e.value);
  }
  return s;
}
